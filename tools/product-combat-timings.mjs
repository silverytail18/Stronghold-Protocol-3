// Gameplay hit schedules are frozen from the new upstream Spine extraction, independent of render loading.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const assets=JSON.parse(await fs.readFile(path.join(root,'data/assets.json'),'utf8')),timings={},sources={};
for(const id of ['char_4185_amoris','char_4186_tmoris']){
  const model=assets.chars[id]?.spine?.front;if(!model?.skel||!model.hits)throw Error('Missing native hit metadata '+id);
  timings[id]=model.hits;sources[id]={skel:model.skel,sha256:createHash('sha256').update(await fs.readFile(path.join(root,'public',model.skel))).digest('hex')};
  for(const times of Object.values(model.hits))if(!Array.isArray(times)||times.some(t=>!Number.isFinite(t)||t<0))throw Error('Invalid native hit times '+id);
}
await fs.writeFile(path.join(root,'shared/product-combat-timings.js'),'// Generated by tools/product-combat-timings.mjs from upstream event metadata.\nexport const PRODUCT_COMBAT_TIMINGS=Object.freeze('+JSON.stringify(timings)+');\nexport const PRODUCT_COMBAT_TIMING_SOURCES=Object.freeze('+JSON.stringify(sources)+');\n');
console.log('Frozen native combat timings for '+Object.keys(timings).length+' operators');
