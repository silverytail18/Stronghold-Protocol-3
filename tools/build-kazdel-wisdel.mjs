// Reuse the pinned upstream unit forms and summon data, without another hand-maintained skill implementation.
import fs from 'node:fs/promises';
import {getData} from '../server/data.js';
import {composeUnitRecord,unitForm,statusKey} from '../shared/standIn.js';
import {atPotential,stripPotential} from '../shared/potential.js';
import assert from 'node:assert/strict';
function leaves(before,after,prefix='',out={}){
 if(JSON.stringify(before)===JSON.stringify(after))return out;
 if(before&&after&&typeof before==='object'&&typeof after==='object'){
  assert.deepEqual(Object.keys(before),Object.keys(after),'Potential must retain the record shape');
  for(const key of Object.keys(before)){
   if(JSON.stringify(before[key])===JSON.stringify(after[key]))continue;
   assert(!key.includes('.'),'Ambiguous potential leaf');
   leaves(before[key],after[key],prefix?prefix+'.'+key:key,out);
  }
 }else out[prefix]=after;
 return out;
}
const data=getData(),charId='char_1035_wisdel',base='chess_kz_wisdel_a',shadow='token_10035_wisdel_wward';
const unit=data.backups.units[charId],chess={},token=structuredClone(data.backups.tokens[shadow]);
for(const golden of [false,true]){
 const slot=data.chess['chess_char_6_diy1_'+(golden?'b':'a')],id=base.replace(/_a$/,golden?'_b':'_a');
 const identity={...slot,chessId:id,baseId:base,goldenId:base.replace(/_a$/,'_b'),isDiy:false,isHidden:false,visible:true,
  identifier:12008,shopSortId:1108,chessType:'NORMAL',bonds:['kazdelShip','preciShip'],garrisonIds:['kz_growth_wisdel_'+(golden?'b':'a')],upgradeChessId:golden?null:base.replace(/_a$/,'_b')};
 delete identity.diyRequirement;delete identity.backup;
 const form=unitForm(data.backups,charId,slot.status);
 const at=potential=>stripPotential(composeUnitRecord(identity,unit,atPotential(form,potential),{skillIndex:2,moduleId:'uniequip_002_wisdel'}));
 const rec=at(6),potDown={};
 for(let potential=1;potential<6;potential++){const step=leaves(at(potential+1),at(potential));if(Object.keys(step).length)potDown[potential-1]=step;}
 if(Object.keys(potDown).length)rec.potDown=potDown;
 for(let potential=1;potential<=6;potential++)assert.deepEqual(stripPotential(atPotential(rec,potential)),at(potential));
 if(!rec?.skill||rec.skills.length!==3)throw Error('Incomplete upstream Wisdel form');
 rec.expansionBatch='kazdel-expansion-v1';rec.kitRef=charId;chess[id]=rec;
 token.variants[id]=structuredClone(token.variants[charId+'@'+statusKey(slot.status)]);
 if(!token.variants[id])throw Error('Missing upstream summon variant');
 token.owners.push(id);
}
token.expansionBatch='kazdel-expansion-v1';
await fs.writeFile(new URL('../server/sim/content/kazdel/wisdel-records.js',import.meta.url),
 '// Generated by tools/build-kazdel-wisdel.mjs from pinned upstream data/backups.json.\nexport const WISDEL_CHESS='+JSON.stringify(chess)+';\nexport const WISDEL_TOKEN='+JSON.stringify(token)+';\n');
console.log('Compiled normal/elite Wisdel and native summon variants.');
