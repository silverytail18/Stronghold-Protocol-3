// Compile the supplemental official M3 records with the upstream normalizer; never substitutes Lv7 values.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {createOfficialUnitBuilders} from '../server/plugins/officialUnitBuilder.js';
import {PRODUCT_MASTERY_SKILLS,PRODUCT_MASTERY_SOURCE} from '../shared/product-mastery-records.js';
import {BATTLE_MASTERY_SKILLS} from '../shared/skill-mastery-records.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=process.argv[2];if(!source)throw Error('Usage: node tools/build-product-mastery.mjs <official table directory>');
const bytes=await fs.readFile(path.join(source,'skill_table.json')),skillTable=JSON.parse(bytes),rangeTable=JSON.parse(await fs.readFile(path.join(source,'range_table.json'),'utf8'));
const{buildSkill}=createOfficialUnitBuilders(message=>{throw Error(message);});const records={...PRODUCT_MASTERY_SKILLS},wanted=new Set();
// Include every official period's preset and DIY/stand-in forms. Common prototype skills with
// only seven source levels have no M3; do not fabricate a level-ten copy of their rank-seven data.
for(const dir of ['','versions/act1autochess','versions/act1autochess-v1_1','versions/act2autochess-v2_1']){
 for(const table of ['chess','backups']){
  const filename=path.join(root,'data',dir,table+'.json');
  try{
   const doc=JSON.parse(await fs.readFile(filename,'utf8'));
   const forms=table==='chess'?Object.values(doc):Object.values(doc.units||{}).flatMap(u=>Object.values(u.forms||{}));
   for(const form of forms)for(const skill of form.skills||[])if(skill.skillId)wanted.add(skill.skillId);
  }catch(error){if(error.code!=='ENOENT')throw error;}
 }
}
const unavailable=[],unsupported=[];let added=0;
for(const id of wanted){
 if(records[id]||BATTLE_MASTERY_SKILLS[id])continue;
 if(!skillTable[id]){unavailable.push(id);continue;}
 if(!skillTable[id].levels?.[9]){unsupported.push(id);continue;}
 records[id]=buildSkill({skillTable,rangeTable},id,10,null,'Official DIY M3');added++;
}
if(unavailable.length)throw Error('Missing official skills: '+unavailable.join(', '));
const skillTableSHA256=createHash('sha256').update(bytes).digest('hex');
const retainedSkillTableSHA256=[...new Set([...(PRODUCT_MASTERY_SOURCE.retainedSkillTableSHA256||[]),PRODUCT_MASTERY_SOURCE.skillTableSHA256])].filter(hash=>hash!==skillTableSHA256);
await fs.writeFile(path.join(root,'shared/product-mastery-records.js'),'// Generated by tools/build-product-mastery.mjs from official client tables.\nexport const PRODUCT_MASTERY_SOURCE='+JSON.stringify({skillTableSHA256,retainedSkillTableSHA256})+';\nexport const PRODUCT_MASTERY_SKILLS='+JSON.stringify(records)+';\n');
console.log(JSON.stringify({wanted:wanted.size,added,records:Object.keys(records).length,noOriginalM3:unsupported}));
